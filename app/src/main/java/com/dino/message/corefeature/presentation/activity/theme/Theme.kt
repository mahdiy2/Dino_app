@OptIn(ExperimentalMaterial3ExpressiveApi::class)
@Composable
fun SecMessageTheme(
    darkTheme: Boolean = isSystemInDarkTheme(),
    appLanguage: AppLanguage = AppLanguage.English,
    // Dynamic color is available on Android 12+
    dynamicColor: Boolean = true,
    content: @Composable () -> Unit
) {

    val context = LocalContext.current
//    val colorScheme = when {
//        dynamicColor && Build.VERSION.SDK_INT >= Build.VERSION_CODES.S -> {
//            val context = LocalContext.current
//            if (darkTheme) dynamicDarkColorScheme(context) else dynamicLightColorScheme(context)
//        }
//
//        darkTheme -> DarkColorScheme
//        else -> LightColorScheme
//    }
//
//    MaterialTheme(
//        colorScheme = colorScheme,
//        typography = Typography,
//        content = content
//    )

    val colors = if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.S) {
        if (darkTheme) dynamicDarkColorScheme(context = context)
        else dynamicLightColorScheme(context = context)
    } else {
        if (darkTheme) DarkColorPalette else LightColorPalette
    }

//    val colors = if (darkTheme) DarkColorPalette else LightColorPalette

    MaterialExpressiveTheme(
        colorScheme = colors,
        typography = appTypography(appLanguage),
        motionScheme = MotionScheme.expressive(),
        shapes = shapes,
        content = content
    )

    // Optional, this part helps you set the statusbar color
    val view = LocalView.current
    if (!view.isInEditMode) {
        SideEffect {
            val window = (view.context as Activity).window
//            window.statusBarColor = colors.surfaceVariant.toArgb()

            WindowCompat.getInsetsController(window, view)
                .isAppearanceLightStatusBars = !darkTheme
        }
    }
}
